@pytest.mark.parametrize("row", ROWS, ids=lambda r: r["id"])
def test_proposed_owned_temporal_operator_contract(row):
    clauses = parse_assertions(row["text"])
    assert clauses
    if row["expected"] == "unsupported":
        assert any(c.unsupported for c in clauses), [
            (c.text, c.status) for c in clauses
        ]
    else:
        assert not any(c.unsupported for c in clauses)
        assert {c.status for c in clauses if c.kind == "assertion"} == set(
            row["expected"] if isinstance(row["expected"], list) else [row["expected"]]
        )
        assert {v for c in clauses for v in c.cves} == set(row["identities"])
        if isinstance(row["expected"], list):
            assert "; ".join(c.text.rstrip(" .") for c in clauses) + "." == row["text"]
            return
        assert len(clauses) == 1
        if row["text"].startswith("If reports are accurate, "):
            assert clauses[0].conditions == ("If reports are accurate",)
            assert clauses[0].text == row["text"][len("If reports are accurate, ") :]
        else:
            assert clauses[0].text == row["text"]


