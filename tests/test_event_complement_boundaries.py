@pytest.mark.parametrize(
    "text,ids,status,unsupported,conflicting,exclusion,admission", CASES
)
def test_sentence_contract(
    text, ids, status, unsupported, conflicting, exclusion, admission
):
    assessment = assess_exploitation([article(text)], ids)
    assert assessment.status == status
    assert bool(assessment.unsupported) == unsupported
    assert assessment.conflicting == conflicting
    assert (
        any("active" in r.assertion_projection.excludes for r in assessment.relations)
        == exclusion
    )
    if admission is not None:
        assert any(c.kind == admission for c in parse_assertions(text))


