@pytest.mark.parametrize("cue", CUES)
@pytest.mark.parametrize("uppercase", [False, True])
def test_relevance_alone_never_establishes_a_factual_event(cue, uppercase):
    text = "The documentation mentions " + (cue.upper() if uppercase else cue) + "."
    assert has_exploitation_relevance(text)
    assert not any(
        c.assertion_status in {"active", "observed"} and not c.unsupported
        for c in parse_assertions(text)
    )
